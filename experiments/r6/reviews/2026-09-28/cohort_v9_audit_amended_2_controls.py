def regenerate(temp, name):
    """The unchanged generator (`live_shape_v10.main`) over a copy of the sources, into a fixture inside the tree (its paths are tree-relative).
    Where the production ledger refuses to reserve the retry (it reconciled the altered release as consuming the slot), that refusal is
    recorded and the fixture is generated again without the retry, so the auditor still meets the altered release."""
    sources = temp/'sources'; shutil.copytree(SOURCES_V4, sources)
    for command in [*sources.glob('*/stages/*/command.json'), *sources.glob('*/stages/*/scope-command.json')]:
        command.write_text(command.read_text().replace(str(SOURCES_V4), str(sources)))  # as the generator itself rewrites them, source to copy
    change_source(name, sources/RELEASE)
    try: return temp/'fixture', {'ledger_reconciled_release_as': generate(sources, temp/'fixture', (RELEASE, RETRY))}
    except ledger.Failure as refused: retry_refused = refused.code
    kind = generate(sources, temp/'fixture-without-retry', (RELEASE,))
    return temp/'fixture-without-retry', {'ledger_reconciled_release_as': kind, 'retry_reservation_refused_by_ledger': retry_refused}


