def audit_at(f, auditor):
    try: result = auditor.audit(f/'runs', f/'ledgers/campaigns')
    except auditor.Rejection as rejection: return {'accepted': False, 'rejected_case': rejection.case, 'detail': str(rejection)[:400]}
    return {'accepted': result['accepted'], 'case_count': result['case_count']}


def change_source(name, run):
    """The release's own source records, altered before the generator reads them (the chain re-hashed; the generator re-seals)."""
    http_path = run/'stages/proposal-1/output/http.json'; http = r6.read_json(http_path); summary = r6.read_json(run/'credential-summary.json')
    if name == 'release_header_send_recorded': http.update(header_sends_started=1, header_send_at_ns=http['connection_started_at_ns']+1)
    elif name == 'release_grant_committed': http.update(grant_committed=True, grant_created_at_ns=http['connection_started_at_ns']+1)
    elif name == 'release_tls_verified': http.update(tls={'verified': True, 'version': 'TLSv1.3'}, tls_verified_at_ns=http['connection_started_at_ns']+1, tls_verify_code=0)
    elif name == 'release_category_outside_connection_phase': http['failure_category'] = summary['failure_category'] = 'credential_format'
    elif name == 'release_nonzero_exit':
        process_path = run/'stages/proposal-1/proposal-1.process.json'; process = r6.read_json(process_path); process['exit_code'] = 1; r6.write_json(process_path, process)
        rows = frozen.events.read(run/'events.ndjson')
        finished = [r for r in rows if r['source'] == 'supervisor' and r['stage'] == 'proposal-1' and r['event'] == 'stage_finished']
        assert len(finished) == 1; finished[0]['payload'] = process; frozen.base.rechain(run, rows)
    elif name.startswith('release_pregrant_'):  # revision 2: one pre-grant field or file contradicted alone
        field = name.removeprefix('release_pregrant_')
        if field in PRE_GRANT_FILES: (run/'stages/proposal-1/output'/PRE_GRANT_FILES[field]).write_text('{}\n')
        else: PRE_GRANT_CHANGES[field](http)
    elif name != 'regenerated_baseline': raise AssertionError(name)
    r6.write_json(http_path, http); r6.write_json(run/'credential-summary.json', summary)


