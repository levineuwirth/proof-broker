#!/usr/bin/env python3
"""Generate `R6AuditControls.lean`: an unchanged copy of the pinned fold plus the six synthetic controls of the qualification-1
audit (proposal revision 2, controls C1-C6).

The fold region is copied byte for byte from `lean-bridge/ProofBroker/Tactic.lean` at the pinned revision `e627efe`, from
`private def fvarOfName` to the end of `closeViaTermModeComparison`: the thirteen declarations the fold uses and nothing else.
Its digest is written beside the generated file, so the copy is checkable. Each control is a local theorem, closed by the pinned
fold with fixed multipliers, and a whole declaration that refers to it by name, as R6's exports do.
"""
import hashlib
import json
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
PIN = 'e627efe'
FOLD_DECLS = ['fvarOfName', 'HypKind', 'matchIntBound?', 'matchIntEqHyp?', 'matchIntNotBound?', 'normalizeHypothesis',
              'intLitExpr', 'buildNonnegProof', 'closeOmegaSubgoal', 'closeViaTermModeFalse', 'GoalKind', 'matchLiaGoal?',
              'closeViaTermModeComparison']

CONTROLS = '''
/-! ## Controls (qualification-1 audit proposal, revision 2). Each local theorem is closed by the pinned fold above. -/

private def runComparison (entries : List (String × Int)) : TacticM Unit := do
  let g ← getMainGoal
  closeViaTermModeComparison g (← g.getType) entries
  replaceMainGoal []

elab "fold_c1" : tactic => runComparison [("h", 1), ("neg_goal", 2)]
elab "fold_c2" : tactic => runComparison [("h", 1), ("neg_goal", 1)]
elab "fold_c3" : tactic => runComparison [("h", 1), ("neg_goal", 1)]
elab "fold_c4" : tactic => runComparison [("h", 1), ("neg_goal", 2)]
elab "fold_c5" : tactic => runComparison [("neg_goal", 1)]
elab "fold_c6" : tactic => runComparison [("neg_goal", 1)]

end R6AuditFold

namespace R6Audit

/-- C1, the review's probe: `neg_goal` doubled does not cancel; contextual `omega` supplies the argument. -/
theorem c1_local (x y : Int) (h : x ≤ y) : x ≤ y := by fold_c1
theorem c1_whole (x y : Int) (h : x ≤ y) : x ≤ y := c1_local x y h

/-- C2, a valid combination with unused arithmetic hypotheses in scope. -/
theorem c2_local (x y z : Int) (h : x ≤ y) (hu1 : z ≤ 5) (hu2 : 0 ≤ z) (hu3 : y ≤ z + 10) : x ≤ y := by fold_c2
theorem c2_whole (x y z : Int) (h : x ≤ y) (hu1 : z ≤ 5) (hu2 : 0 ≤ z) (hu3 : y ≤ z + 10) : x ≤ y :=
  c2_local x y z h hu1 hu2 hu3

/-- C3, casts and an opaque product: the sum cancels once `↑(a + b)` is read as `↑a + ↑b`. -/
theorem c3_local (a b : Nat) (x y : Int) (h : ((a + b : Nat) : Int) + x * y ≤ 4) : (a : Int) + (b : Int) + x * y ≤ 4 := by
  fold_c3
theorem c3_whole (a b : Nat) (x y : Int) (h : ((a + b : Nat) : Int) + x * y ≤ 4) : (a : Int) + (b : Int) + x * y ≤ 4 :=
  c3_local a b x y h

/-- C4, the exported structure: the whole passes one of its own hypotheses to the local theorem, and has another it does not pass. -/
theorem c4_local (x y : Int) (h : x ≤ y) : x ≤ y := by fold_c4
theorem c4_whole (p q : Int) (hpq : p ≤ q) (hextra : 0 ≤ p) : p ≤ q := c4_local p q hpq

/-- C5, a let-bound value defined through a hypothesis: `hpos` mentions `v := Classical.choose h`. -/
theorem c5_local (h : ∃ n : Int, n ≤ 3) : let v := Classical.choose h; v ≤ v + 1 := by
  intro v
  fold_c5
theorem c5_whole (h : ∃ n : Int, n ≤ 3) : let v := Classical.choose h; v ≤ v + 1 := c5_local h

/-- C6, a lossy abstraction: `omega` reads `x % 2`, and generalizing it to an atom loses `x % 2 < 2`. -/
theorem c6_local (x : Int) : x % 2 < 2 := by fold_c6
theorem c6_whole (x : Int) : x % 2 < 2 := c6_local x

end R6Audit
'''


def fold_region(source: str) -> str:
    lines = source.splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l.startswith('private def fvarOfName '))
    # the region ends just before the docstring of `closeViaTermMode`, the next declaration after the fold
    stop = next(i for i, l in enumerate(lines) if l.startswith('private def closeViaTermMode '))
    while stop > 0 and not lines[stop - 1].startswith('/--'):
        stop -= 1
    stop -= 1
    region = ''.join(lines[start:stop])
    heads = [l.split()[2] for l in lines[start:stop] if l.startswith(('private def ', 'private inductive '))]
    assert heads == FOLD_DECLS, heads
    return region


def main():
    source = subprocess.run(['git', '-C', str(REPO), 'show', f'{PIN}:lean-bridge/ProofBroker/Tactic.lean'],
                            capture_output=True, text=True, check=True).stdout
    region = fold_region(source)
    header = ('import Lean\nimport ProofBroker.TermMode\n\n'
              '/-! Generated by `make_controls.py`. The region between the markers is copied byte for byte from\n'
              f'    `lean-bridge/ProofBroker/Tactic.lean` at `{PIN}`. -/\n\n'
              'namespace R6AuditFold\n\nopen Lean Lean.Elab.Tactic Lean.Meta\n\n-- BEGIN pinned fold\n')
    text = header + region + '-- END pinned fold\n' + CONTROLS
    out = HERE / 'R6AuditControls.lean'
    out.write_text(text)
    (HERE / 'R6AuditControls.provenance.json').write_text(json.dumps({
        'pin': PIN, 'source': 'lean-bridge/ProofBroker/Tactic.lean', 'declarations': FOLD_DECLS,
        'region_sha256': hashlib.sha256(region.encode()).hexdigest(),
        'generated_sha256': hashlib.sha256(text.encode()).hexdigest()}, indent=1) + '\n')
    print(out, len(region.splitlines()), 'fold lines')


if __name__ == '__main__':
    main()
