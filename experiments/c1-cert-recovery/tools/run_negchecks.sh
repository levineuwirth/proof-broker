#!/usr/bin/env bash
# Negative checks over the corpus, AS A GATE.
#
# For every captured IR: run diag/negcheck.exe, which checks the shipped
# verification interfaces against an independently computed expectation and
# exits nonzero when they disagree. This script fails when the executable
# fails, when a result file is missing, when a result's own `gate.ok` is
# false, or when a case that has an expectation has no result at all.
#
# The previous version of this script reported `FAIL <id>` and still exited 0,
# because `cmd && echo ok || echo FAIL` makes the pipeline succeed and nothing
# looked at the exit code afterwards (C1 review, finding 3). It also ran
# happily with no `logs/STAMP`. Both are fixed, and the fix is SELF-TESTED:
#
#     NEGCHECK_BIN=tools/negcheck_fault_stub.sh tools/run_negchecks.sh
#
# must exit nonzero. `logs/negcheck_gate_selftest.txt` records that it does.
set -u
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# The executables must be the ones that link the CURRENT SDK. Building them is
# part of the gate, not a step someone remembers: a stale statically-linked
# negcheck.exe reported the previous SDK's behavior for a whole pass once
# already (R6 checkpoint-2 review, finding 3).
# ALWAYS, not "unless NEGCHECK_BIN is set". Gating the preflight on the
# fault-injection seam meant any caller supplying its own executable skipped
# the build check entirely — a hole in the gate, found by the preflight test's
# own positive control. The fault-injection self-test now lets the (fast,
# already up-to-date) build run and injects only the executable.
"${BUILD_DIAG:-tools/build_diag.sh}" > /dev/null || {
  echo "negchecks: diagnostic build failed — refusing to run" >&2; exit 2; }

STAMP_FILE=logs/STAMP
[ -r "$STAMP_FILE" ] || { echo "negchecks: no $STAMP_FILE" >&2; exit 2; }
STAMP="$(cat "$STAMP_FILE")"
[ -n "$STAMP" ] || { echo "negchecks: empty $STAMP_FILE" >&2; exit 2; }
OUT="raw/$STAMP"
mkdir -p "$OUT"

NEG="${NEGCHECK_BIN:-../../_build/default/experiments/c1-cert-recovery/diag/negcheck.exe}"
[ -x "$NEG" ] || { echo "negchecks: $NEG is not executable" >&2; exit 2; }

# Expectation manifest: generated by a CHECKED command into a file, validated,
# and only then consumed. Reading it from a process substitution discarded the
# generator's exit status entirely — a generator that died emitted no cases and
# the runner reported "0 passed, 0 failures" and exited 0
# (R6 checkpoint-2 review, finding 4).
GEN="${NEGCHECK_EXPECTATIONS:-python3 tools/negcheck_expectations.py}"
MANIFEST="$OUT/expectations.txt"
$GEN > "$MANIFEST" 2>"$OUT/expectations.err"; gen_rc=$?
if [ "$gen_rc" -ne 0 ]; then
  echo "negchecks: expectation generator failed (exit $gen_rc)" >&2
  sed 's/^/  /' "$OUT/expectations.err" >&2
  exit 2
fi
if [ ! -s "$MANIFEST" ]; then
  echo "negchecks: expectation generator produced no cases" >&2
  exit 2
fi
if ! awk 'NF != 2 || $2 !~ /^(sat|unsat|no-ir)$/ { exit 1 }' "$MANIFEST"; then
  echo "negchecks: malformed expectation manifest ($MANIFEST)" >&2
  exit 2
fi
n_expected=$(wc -l < "$MANIFEST")
echo "negchecks: $n_expected case(s) in the expectation manifest"

fails=0
checked=0
weakened=()

while read -r id expectation; do
  ir="ir/$id.json"
  if [ "$expectation" = no-ir ]; then
    if [ -r "$ir" ]; then
      echo "UNEXPECTED-IR $id (declared unreifiable, but $ir exists)"
      fails=$((fails + 1))
    else
      checked=$((checked + 1))
      echo "ok (no IR)   $id"
    fi
    continue
  fi
  if [ ! -r "$ir" ]; then
    echo "MISSING-IR   $id (no captured IR; every case with an expectation must have one)"
    fails=$((fails + 1))
    continue
  fi
  args=()
  [ "$expectation" = sat ] && args+=(--expect-sat)
  rm -f "$OUT/$id.negcheck.json"
  set +e
  "$NEG" "${args[@]}" "$ir" "$OUT" "$id" \
    > "$OUT/$id.negcheck.stdout" 2> "$OUT/$id.negcheck.stderr"
  rc=$?
  set -e
  if [ ! -s "$OUT/$id.negcheck.json" ]; then
    echo "NO-RESULT    $id (exit $rc; no $OUT/$id.negcheck.json)"
    fails=$((fails + 1))
    continue
  fi
  gate_ok=$(python3 -c "
import json,sys
try: print(json.load(open(sys.argv[1]))['gate']['ok'])
except Exception as e: print('unreadable:%s' % e)
" "$OUT/$id.negcheck.json")
  if [ "$rc" -ne 0 ] || [ "$gate_ok" != "True" ]; then
    echo "GATE-FAIL    $id (exit $rc, gate.ok=$gate_ok)"
    sed 's/^/               /' "$OUT/$id.negcheck.stderr" | head -6
    fails=$((fails + 1))
    continue
  fi
  # Tracked separately, NOT a gate condition: a case whose statement is true
  # but on which every adapter answered sat. That means the reified IR was
  # weakened (a hypothesis the reifier could not represent was dropped), so
  # `sat` is a statement about the weakened IR and NOT evidence that the
  # original Lean goal is unprovable.
  if [ "$expectation" = unsat ]; then
    if python3 -c "
import json,sys
d=json.load(open(sys.argv[1]))
a=d['adapters']
sys.exit(0 if all(v['outcome']=='failed' and (v.get('failure') or {}).get('kind')=='sat_returned' for v in a.values()) else 1)
" "$OUT/$id.negcheck.json"; then
      weakened+=("$id")
    fi
  fi
  checked=$((checked + 1))
  echo "ok           $id"
done < "$MANIFEST"

echo
echo "negchecks: $checked case(s) passed the gate, $fails failure(s)"
if [ "$((checked + fails))" -ne "$n_expected" ]; then
  echo "negchecks: only $((checked + fails)) of $n_expected manifest case(s) \
were reached" >&2
  fails=$((fails + 1))
fi
if [ ${#weakened[@]} -gt 0 ]; then
  echo "negchecks: TRUE goals on which every adapter answered sat — the reified"
  echo "           IR was weakened, so sat is not evidence the goal is false:"
  printf '             %s\n' "${weakened[@]}"
fi
[ "$fails" -eq 0 ] || exit 1
